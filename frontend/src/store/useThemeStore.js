export const useThemeStore = create((set) => ({
  theme: localStorage.getItem("chat_accent_theme") || "cyan",
  isThemeModalOpen: false,

  setTheme: (themeId) => {
    localStorage.setItem("chat_accent_theme", themeId);
    set({ theme: themeId });
  },

  openThemeModal: () => set({ isThemeModalOpen: true }),
  closeThemeModal: () => set({ isThemeModalOpen: false }),
  toggleThemeModal: () => set((state) => ({ isThemeModalOpen: !state.isThemeModalOpen })),

  getTheme: () => {
    const currentThemeId = localStorage.getItem("chat_accent_theme") || "cyan";
    return THEMES.find((t) => t.id === currentThemeId) || THEMES[0];
  },
}));
